import fs from 'node:fs';
import assert from 'node:assert/strict';
import { calculateRoom } from '../apps/frontend/src/lib/quickEstimate.ts';
const fixtures=JSON.parse(fs.readFileSync(new URL('../tests/quick-legacy-fixtures.json',import.meta.url),'utf8'));
for(const fixture of fixtures) assert.deepEqual(calculateRoom(fixture.room),fixture.expected,`${fixture.room.room_type} width=${fixture.room.width_ft}`);
console.log(`${fixtures.length} Quick Estimate parity fixtures passed against the original compiled frontend.`);
const room={id:'check',room_type:'hallway',label:'Entry',width_ft:10,height_ft:8,options:{mirror_sf:10,console_lf:2}};
const changed=calculateRoom(room,{quick_estimate:{wall_rate:100,mirror_rate:70,mirror_installation:{rate_small:90,rate_large:75,threshold_sf:15}},cabinet_types:{entry_console:{base_rate:1600}}});
assert.equal(changed.find(i=>i.name==='Wall Panels').total_price,8000);
assert.equal(changed.find(i=>i.name==='Mirror').total_price,700);
assert.equal(changed.find(i=>i.name==='Mirror Delivery & Installation').total_price,900);
assert.equal(changed.find(i=>i.name==='Entry Console').total_price,3200);
console.log('Saved Quick Estimate rates are applied without changing the original room formulas.');
